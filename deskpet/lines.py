def add_chatter(level, more):
    """扩展加闲聊台词：好感等级 >= level 时才会说。"""
    CHATTER.append((level, list(more)))


def pick(table, level):
    """从按等级分段的表里随机挑一句（只挑已解锁的）。"""
    pool = [line for lv, lines in table for line in lines if level >= lv]
    return random.choice(pool) if pool else ""


def one(lines):
    return random.choice(lines)
